def word_Decoder(head):
  #To Do
  new_head = None
  y = 13 % count(head)

  for i in range(y, count(head), y):
    if new_head == None:
      n = nodeAt(head, i)
      n1 = Node(n.elem)
      new_head = n1
      temp = new_head
    else:
      n = nodeAt(head, i)
      n1 = Node(n.elem)
      temp.next = n1
      temp = temp.next

  temp1 = new_head
  revHead = None
  while temp1 != None:
    n = temp1.next
    temp1.next = revHead
    revHead = temp1
    temp1 = n
  return revHead




