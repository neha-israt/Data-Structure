def compress_matrix(mat):
   row, col = mat.shape
   k = 0
   comp_mat = np.zeros((2,2), dtype = int)
   for i in range(0, row, 2):
    x = 0
    for j in range(0, col, 2):
      comp_mat[k][x]= mat[i][j] + mat[i+1][j] + mat[i][j+1] + mat[i+1][j+1]
      x += 1
    k += 1

   return comp_mat





