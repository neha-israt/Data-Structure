def play_game(arena):
  #TO DO
  row, col = arena.shape

  cell_count = 0
  for i in range(row):
    for j in range(col):
      if arena[i][j] % 50 == 0 and arena[i][j] != 0:
        if 0 <= i-1 < row and arena[i-1][j] == 2:
          cell_count += 1
        if 0 <= j+1 < col and arena[i][j+1] == 2 :
          cell_count += 1
        if 0 <= i+1 < row and arena[i+1][j] == 2 :
          cell_count += 1
