def conditional_reverse(stack):
  #To Do
  s1 = Stack()
  while st.isEmpty() == False:
    if s1.isEmpty() == True:
      s1.push(st.pop())
    else:
      popped = st.pop()

      if popped == s1.peek():
        continue
      else:
        s1.push(popped)
  return s1




