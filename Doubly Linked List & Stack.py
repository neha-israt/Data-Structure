def remove_block(stack, n):
  s1 = Stack()
  count = 0
  while True:
    if st.isEmpty() == False:
      count += 1
      b = st.pop()
      if count == n:
        continue
      else:
        s1.push(b)
    else:
      break

  while s1.isEmpty() == False:
    st.push(s1.pop())
  return st

