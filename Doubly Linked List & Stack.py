def diamond_count(stack,string):
  #TO DO
  count = 0
  for i in range(len(string)):
    if string[i] == '<':
      stack.push(string[i])
    elif string[i] == '>':
      if stack.isEmpty() == False:
        b = stack.pop()
        if b == '<' and string[i] == '>':
          count += 1
  return count



